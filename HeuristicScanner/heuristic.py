"""
GitHub Repository Scanner for AI-related content.

Uses the GitHub API instead of cloning. Scans README, CONTRIBUTING, AGENTS.md,
and commit messages for AI-related keywords and AI commit-trailer disclosures
(Co-Authored-By: Claude, Assisted-by: Copilot, etc.).
"""

