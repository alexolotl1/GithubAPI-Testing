    import argparse

    BASE_DIR = os.path.dirname(os.path.abspath(__file__))
    parser = argparse.ArgumentParser(description="Keyword + AI-trailer scan of a repo sample")
    parser.add_argument('--input', default=os.path.join(BASE_DIR, "sample.json"))
    parser.add_argument('--output', default=os.path.join(BASE_DIR, "ai_scan_results.json"))
    args = parser.parse_args()

    if not Path(args.input).exists():
        print(f"Error: {args.input} not found!")
        exit(1)

    scanner = GitHubAPIScanner(args.input, args.output)
    scanner.run_scan()
