# 'cursor'/'devin' are phrase-gated, not bare words: bare 'cursor' matched a
# literal database cursor in one commit, and 'devin' is a common first name.
AI_KEYWORDS = {
    "gpt": 10,
    "copilot": 10,
    "chatgpt": 10,
    "ai-generated": 12,
    "ai generated": 12,
    "openai": 10,
    "claude": 9,
    "gemini": 8,
    "codellama": 9,
    "codegen": 8,
    "anthropic": 8,
    "ollama": 8,
    "vertexai": 8,
    "autogenerated": 10,
    "generated by": 9,
    "ai-assisted": 9,
    "ai assisted": 9,
    "llm": 8,
    "transformers": 7,
    "langchain": 8,
    "huggingface": 7,
    "mistral": 8,
    "llama": 8,
    "cursor ai": 8,
    "cursor agent": 9,
    "using cursor": 6,
    "devin ai": 9,
    "devin.ai": 9,
    "codewhisperer": 9,
}

AI_SCORE_THRESHOLD = 15

# Structured AI coding-agent commit trailers, e.g. "Co-Authored-By: Claude
# <noreply@anthropic.com>" — a much higher-confidence signal than a bare
# keyword mention.
AI_TRAILER_RE = re.compile(
    r'(?:co-authored-by|assisted-by|generated-by|reviewed-by)\s*:\s*'
    r'[^\n<]*?(claude|copilot|cursor(?:\s*agent)?|codex|devin|gemini|chatgpt|'
    r'gpt-\d|anthropic|openai|codewhisperer|amazon\s*q|tabnine|windsurf)',
    re.IGNORECASE,
)
AI_TRAILER_SCORE = 20  # per matching trailer line, > any single keyword

EXTRA_FILES_TO_SCAN = [
    "CONTRIBUTING.md",
    "CONTRIBUTING.rst",
    "AGENTS.md",
    "CODEOWNERS",
    ".github/CONTRIBUTING.md",
    ".github/copilot-instructions.md",
]

